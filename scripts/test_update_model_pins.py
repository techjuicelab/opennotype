#!/usr/bin/env python3
"""Offline checks for the local-model pin generator; no network or model download."""
import hashlib
import importlib.util
from pathlib import Path
import re
import unittest

SPEC = importlib.util.spec_from_file_location("model_pins", Path(__file__).with_name("update-model-pins.py"))
pins = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(pins)
COMMIT = "0123456789abcdef0123456789abcdef01234567"


def git_oid(content):
    return hashlib.sha1(b"blob %d\0" % len(content) + content).hexdigest()


class ModelPinTests(unittest.TestCase):
    def test_entries_take_lfs_digests_and_hash_small_files_after_checking_their_git_object(self):
        small = b'{"vocab": 1}'
        weights = "a" * 64
        items = [
            {"type": "file", "path": "m/weights.bin", "size": 9, "lfs": {"oid": weights, "size": 9}},
            {"type": "file", "path": "m/config.json", "size": len(small), "oid": git_oid(small)},
        ]
        result = pins.entries("owner/repo", COMMIT, items, read=lambda path: small)
        self.assertEqual([("m/config.json", len(small), hashlib.sha256(small).hexdigest()),
                          ("m/weights.bin", 9, weights)], result)

    def test_entries_reject_content_that_differs_from_the_listed_commit(self):
        listed = b"listed"
        item = {"type": "file", "path": "config.json", "size": len(listed), "oid": git_oid(listed)}
        with self.assertRaisesRegex(ValueError, "git object mismatch"):
            pins.entries("owner/repo", COMMIT, [item], read=lambda path: b"served")
        with self.assertRaisesRegex(ValueError, "size mismatch"):
            pins.entries("owner/repo", COMMIT, [item], read=lambda path: b"longer content")
        with self.assertRaisesRegex(ValueError, "no files pinned"):
            pins.entries("owner/repo", COMMIT, [])

    def test_render_writes_every_model_tokenizer_and_speaker_pin(self):
        one = [("x/file.bin", 3, "b" * 64)]
        data = {pins.WHISPER_REPOSITORY: {"commit": COMMIT, "files": {
            variant: [(f"{variant}/coremldata.bin", 3, "c" * 64)] for variant, _ in pins.WHISPER_MODELS.values()}}}
        for _, repository in pins.WHISPER_MODELS.values():
            data[repository] = {"commit": COMMIT, "files": [("tokenizer.json", 3, "d" * 64)]}
        data[pins.SPEAKER_REPOSITORY] = {"commit": COMMIT, "files": one}
        swift = pins.render(data, "2026-11-03")
        self.assertIn("enum LocalModelManifest {", swift)
        for case, (variant, repository) in pins.WHISPER_MODELS.items():
            self.assertIn(f"case .{case}: [", swift)
            self.assertIn(f'"{variant}/coremldata.bin"', swift)
            self.assertIn(f'LocalModelPin(repository: "{repository}", revision: "{COMMIT}")', swift)
        self.assertIn(f'repository: "{pins.SPEAKER_REPOSITORY}"', swift)
        self.assertEqual(len(re.findall(r"\.init\(", swift)), 3 + 3 + 1)

    def test_render_refuses_values_that_could_escape_a_swift_string(self):
        with self.assertRaises(ValueError):
            pins.swift_string('folder"/file')
        with self.assertRaises(SystemExit):
            pins.parse_revisions(["owner/repo=main"])
        self.assertEqual({"owner/repo": COMMIT}, pins.parse_revisions([f"owner/repo={COMMIT}"]))

    def test_checked_in_manifest_matches_the_generator_layout(self):
        manifest = pins.OUTPUT.read_text(encoding="utf-8")
        self.assertTrue(manifest.startswith("// Generated by scripts/update-model-pins.py"))
        commits = re.findall(r'revision: "([0-9a-f]+)"', manifest)
        self.assertEqual(5, len(commits))
        self.assertTrue(all(re.fullmatch(r"[0-9a-f]{40}", commit) for commit in commits))
        for variant, repository in pins.WHISPER_MODELS.values():
            self.assertIn(f'"{variant}/TextDecoder.mlmodelc/coremldata.bin"', manifest)
            self.assertIn(f'repository: "{repository}"', manifest)
        for folder in pins.SPEAKER_FOLDERS:
            self.assertIn(f'"{folder}/coremldata.bin"', manifest)


if __name__ == "__main__":
    unittest.main()
