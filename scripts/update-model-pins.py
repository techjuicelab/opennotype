#!/usr/bin/env python3
"""Pin the public local-model files that OpenNoType downloads.

Writes Sources/OpenNoTypeCore/LocalAudio/LocalModelManifest.swift with the repository commit,
size and SHA-256 of every file the app downloads for Whisper models, tokenizers and the optional
speaker models. The app downloads only these commits and rejects any file that does not match.

    python3 scripts/update-model-pins.py                      # pin each repository's current main
    python3 scripts/update-model-pins.py --revision REPO=SHA   # keep or choose a specific commit

Only public metadata and small non-LFS files are fetched; model weights are not downloaded.
"""
import argparse
import datetime
import hashlib
import json
from pathlib import Path
import re
import sys
import urllib.parse
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "Sources/OpenNoTypeCore/LocalAudio/LocalModelManifest.swift"
HUB = "https://huggingface.co"
COMMIT = re.compile(r"^[0-9a-f]{40}$")
DIGEST = re.compile(r"^[0-9a-f]{64}$")
# Tokenizer files read by WhisperKit's local tokenizer loader; tokenizer.json is required.
TOKENIZER_FILES = ("config.json", "tokenizer.json", "tokenizer_config.json")
WHISPER_REPOSITORY = "argmaxinc/whisperkit-coreml"
SPEAKER_REPOSITORY = "FluidInference/speaker-diarization-coreml"
# LocalSpeechModel case -> (WhisperKit variant folder, tokenizer repository)
WHISPER_MODELS = {
    "largeV3": ("openai_whisper-large-v3-v20240930_626MB", "openai/whisper-large-v3"),
    "small": ("openai_whisper-small", "openai/whisper-small"),
    "base": ("openai_whisper-base", "openai/whisper-base"),
}
SPEAKER_FOLDERS = ("pyannote_segmentation.mlmodelc", "wespeaker_v2.mlmodelc")


def fetch(url, limit=64_000_000):
    request = urllib.request.Request(url, headers={"User-Agent": "OpenNoType-model-pins"})
    with urllib.request.urlopen(request, timeout=60) as response:
        data = response.read(limit + 1)
    if len(data) > limit:
        raise ValueError(f"response_too_large: {url}")
    return data


def api(path):
    return json.loads(fetch(f"{HUB}/api/models/{path}"))


def main_commit(repository):
    commit = api(repository)["sha"]
    if not COMMIT.match(commit):
        raise ValueError(f"unexpected commit for {repository}: {commit}")
    return commit


def tree(repository, revision, folder):
    quoted = urllib.parse.quote(folder)
    return [item for item in api(f"{repository}/tree/{revision}/{quoted}?recursive=true") if item["type"] == "file"]


def entries(repository, revision, items, read=None):
    """Size and SHA-256 per file. LFS files carry their SHA-256; small files are hashed here."""
    read = read or (lambda path: fetch(f"{HUB}/{repository}/resolve/{revision}/{urllib.parse.quote(path)}"))
    result = []
    for item in sorted(items, key=lambda value: value["path"]):
        lfs = item.get("lfs")
        if lfs:
            digest, size = lfs["oid"], int(lfs["size"])
        else:
            content = read(item["path"])
            size = len(content)
            if size != int(item["size"]):
                raise ValueError(f"size mismatch for {item['path']}")
            # The listed oid is the git blob SHA-1; check it before trusting the content.
            blob = hashlib.sha1(b"blob %d\0" % size + content).hexdigest()
            if blob != item["oid"]:
                raise ValueError(f"git object mismatch for {item['path']}")
            digest = hashlib.sha256(content).hexdigest()
        if not DIGEST.match(digest):
            raise ValueError(f"unexpected digest for {item['path']}")
        result.append((item["path"], size, digest))
    if not result:
        raise ValueError(f"no files pinned in {repository}@{revision}")
    return result


def swift_string(value):
    if not re.match(r"^[A-Za-z0-9_./@-]+$", value):
        raise ValueError(f"unexpected characters: {value}")
    return f'"{value}"'


def render_files(files, indent):
    pad = " " * indent
    return "\n".join(f"{pad}.init({swift_string(path)}, {size}, {swift_string(digest)})," for path, size, digest in files)


def render(pins, today):
    whisper_revision = pins[WHISPER_REPOSITORY]
    lines = [
        f"// Generated by scripts/update-model-pins.py on {today}. Do not edit by hand.",
        "// Every file the app downloads for local transcription and speaker filtering, at a fixed",
        "// commit, with its size and SHA-256. Downloads are rejected unless every file matches.",
        "",
        "enum LocalModelManifest {",
        f"    static let whisperModels = LocalModelPin(repository: {swift_string(WHISPER_REPOSITORY)},",
        f"                                             revision: {swift_string(whisper_revision['commit'])})",
        "",
        "    static func whisperFiles(_ model: LocalSpeechModel) -> [LocalModelFile] {",
        "        switch model {",
    ]
    for case, (variant, _) in WHISPER_MODELS.items():
        lines += [f"        case .{case}: [", render_files(whisper_revision["files"][variant], 12), "        ]"]
    lines += ["        }", "    }", "", "    static func tokenizer(_ model: LocalSpeechModel) -> LocalModelPin {", "        switch model {"]
    for case, (_, repository) in WHISPER_MODELS.items():
        lines.append(f"        case .{case}: LocalModelPin(repository: {swift_string(repository)}, "
                     f"revision: {swift_string(pins[repository]['commit'])})")
    lines += ["        }", "    }", "", "    static func tokenizerFiles(_ model: LocalSpeechModel) -> [LocalModelFile] {",
              "        switch model {"]
    for case, (_, repository) in WHISPER_MODELS.items():
        lines += [f"        case .{case}: [", render_files(pins[repository]["files"], 12), "        ]"]
    speaker = pins[SPEAKER_REPOSITORY]
    lines += ["        }", "    }", "",
              f"    static let speakerModels = LocalModelPin(repository: {swift_string(SPEAKER_REPOSITORY)},",
              f"                                             revision: {swift_string(speaker['commit'])})",
              "", "    static let speakerFiles: [LocalModelFile] = [", render_files(speaker["files"], 8), "    ]", "}", ""]
    return "\n".join(lines)


def collect(revisions):
    pins = {}
    commit = revisions.get(WHISPER_REPOSITORY) or main_commit(WHISPER_REPOSITORY)
    pins[WHISPER_REPOSITORY] = {"commit": commit, "files": {
        variant: entries(WHISPER_REPOSITORY, commit, tree(WHISPER_REPOSITORY, commit, variant))
        for variant, _ in WHISPER_MODELS.values()}}
    for _, repository in WHISPER_MODELS.values():
        commit = revisions.get(repository) or main_commit(repository)
        listed = [item for item in tree(repository, commit, "") if item["path"] in TOKENIZER_FILES]
        if "tokenizer.json" not in {item["path"] for item in listed}:
            raise ValueError(f"tokenizer.json missing in {repository}@{commit}")
        pins[repository] = {"commit": commit, "files": entries(repository, commit, listed)}
    commit = revisions.get(SPEAKER_REPOSITORY) or main_commit(SPEAKER_REPOSITORY)
    speaker = []
    for folder in SPEAKER_FOLDERS:
        speaker += tree(SPEAKER_REPOSITORY, commit, folder)
    pins[SPEAKER_REPOSITORY] = {"commit": commit, "files": entries(SPEAKER_REPOSITORY, commit, speaker)}
    return pins


def parse_revisions(values):
    revisions = {}
    for value in values:
        repository, _, commit = value.partition("=")
        if not repository or not COMMIT.match(commit):
            raise SystemExit(f"--revision expects REPO=<40-hex commit>: {value}")
        revisions[repository] = commit
    return revisions


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--revision", action="append", default=[], help="REPO=COMMIT to pin instead of main")
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args(argv)
    pins = collect(parse_revisions(args.revision))
    args.output.write_text(render(pins, datetime.date.today().isoformat()), encoding="utf-8")
    for repository, pin in pins.items():
        files = pin["files"]
        count = sum(len(group) for group in files.values()) if isinstance(files, dict) else len(files)
        print(f"{repository}@{pin['commit']}: {count} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
